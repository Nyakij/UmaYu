//! A plain-markdown digest of the owned roster, with names resolved and support effects read at
//! the owned level, for AI assistants that answer by reading files (OpenCode, Claude Code).
//! Written to knowledge/digest/owned.md whenever the app loads data and the content changed.

use std::fmt::Write;
use std::path::PathBuf;

use crate::App;
use crate::knowledge::effect_at;

pub const DIGEST_FILE: &str = "knowledge/digest/owned.md";

impl App {
    pub(crate) fn roster_digest(&self) -> String {
        let mut md = String::new();
        let kb = &self.kb;
        let _ = writeln!(md, "# Owned roster digest\n");
        let _ = writeln!(
            md,
            "Generated by the UmaYu app from account/*.md and knowledge/data (uma.guide Global data{}). Don't edit: it is rewritten on every load.\n",
            kb.built
                .as_ref()
                .map(|b| format!(", built {}", &b[..10.min(b.len())]))
                .unwrap_or_default()
        );
        let _ = writeln!(
            md,
            "Server: {}. {} umas, {} support cards.\n",
            self.roster.server.as_deref().unwrap_or("unknown"),
            self.roster.umas.len(),
            self.roster.cards.len()
        );

        // The live Champions Meeting schedule (official news over Umalator's estimates), which the
        // app fetches into a cache outside this folder.
        let cms: Vec<_> = kb
            .upcoming_cms(&crate::ui_util::today())
            .into_iter()
            .take(4)
            .collect();
        if !cms.is_empty() {
            let _ = writeln!(md, "## Champions Meeting schedule\n");
            let _ = writeln!(
                md,
                "The next Champions Meetings. \"Announced\" rows come from the official news (umamusume.com) and are final; \"estimated\" rows are Umalator's guess and may change. Times are UTC.\n"
            );
            let _ = writeln!(
                md,
                "| Cup | Round 1 | League selection | Ends | Course | Conditions | Status | Won't activate |"
            );
            let _ = writeln!(md, "|---|---|---|---|---|---|---|---|");
            let time = |t: Option<i64>| {
                t.map(|t| {
                    format!(
                        "{} {}",
                        crate::live::utc_date(t),
                        crate::live::fmt_utc(t).split(" UTC").next().unwrap_or("")
                    )
                })
                .unwrap_or_else(|| "—".into())
            };
            for e in cms {
                let disabled: Vec<String> = e
                    .disabled_skills
                    .iter()
                    .map(|s| kb.skill_name(*s))
                    .collect();
                let _ = writeln!(
                    md,
                    "| {} | {} | {} | {} | {} | {} | {} | {} |",
                    e.name,
                    e.round1
                        .map_or_else(|| format!("{} (estimated)", e.date), |t| time(Some(t))),
                    time(e.league_selection),
                    time(e.ends),
                    e.course_name,
                    e.conditions,
                    if e.announced {
                        "announced".to_string()
                    } else {
                        format!("estimated ({})", e.source.label())
                    },
                    if disabled.is_empty() {
                        "—".into()
                    } else {
                        disabled.join(", ")
                    }
                );
            }
            let _ = writeln!(md);
        }

        // Compact tables first, so list and comparison questions need one read and see every row.
        let _ = writeln!(md, "## At a glance: umas\n");
        let _ = writeln!(
            md,
            "One row per owned uma. Aptitude grades, S best to G worst. Growth is the stat growth bonus.\n"
        );
        let _ = writeln!(
            md,
            "| Uma | Outfit | ★ | Pot | Turf | Dirt | Sprint | Mile | Medium | Long | Front | Pace | Late | End | Growth |"
        );
        let _ = writeln!(
            md,
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"
        );
        for u in &self.roster.umas {
            let Some(i) = kb.umas.get(&u.id) else {
                continue;
            };
            let a = &i.aptitude;
            let growth: Vec<String> = ["Spd", "Sta", "Pow", "Gut", "Wit"]
                .iter()
                .zip(i.growth)
                .filter(|(_, g)| *g != 0)
                .map(|(n, g)| format!("{n}+{g}"))
                .collect();
            let _ = writeln!(
                md,
                "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
                u.name,
                u.outfit,
                u.stars,
                u.potential,
                a.turf,
                a.dirt,
                a.sprint,
                a.mile,
                a.medium,
                a.long,
                a.front,
                a.pace,
                a.late,
                a.end,
                growth.join(" ")
            );
        }
        let _ = writeln!(md, "\n## At a glance: support cards\n");
        let _ = writeln!(
            md,
            "One row per owned card. Effects are at the owned level.\n"
        );
        let _ = writeln!(
            md,
            "| Card | Title | Rarity | Type | LB | Lv | Friendship | Training | Specialty | Race | Hint freq |"
        );
        let _ = writeln!(md, "|---|---|---|---|---|---|---|---|---|---|---|");
        for c in &self.roster.cards {
            let Some(i) = kb.cards.get(&c.id) else {
                continue;
            };
            let v = |k: u32| i.effect(k, u32::from(c.level)).unwrap_or(0);
            use crate::knowledge::effect as fx;
            let _ = writeln!(
                md,
                "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
                c.uma,
                c.title,
                c.rarity.label(),
                c.card_type.label(),
                if c.is_mlb() {
                    "MLB".to_string()
                } else {
                    c.lb.to_string()
                },
                c.level,
                v(fx::FRIENDSHIP),
                v(fx::TRAINING),
                v(fx::SPECIALTY),
                v(fx::RACE),
                v(fx::HINT_FREQ)
            );
        }
        let _ = writeln!(md);

        let _ = writeln!(md, "## Umas\n");
        for u in &self.roster.umas {
            let _ = writeln!(
                md,
                "### {} [{}] — {}★, Potential {} (id {})",
                u.name, u.outfit, u.stars, u.potential, u.id
            );
            let Some(i) = kb.umas.get(&u.id) else {
                let _ = writeln!(md, "- No knowledge data for this outfit.\n");
                continue;
            };
            let a = &i.aptitude;
            let _ = writeln!(
                md,
                "- Aptitude: Turf {}, Dirt {} | Sprint {}, Mile {}, Medium {}, Long {} | Front {}, Pace {}, Late {}, End {}",
                a.turf, a.dirt, a.sprint, a.mile, a.medium, a.long, a.front, a.pace, a.late, a.end
            );
            let growth: Vec<String> = ["Speed", "Stamina", "Power", "Guts", "Wit"]
                .iter()
                .zip(i.growth)
                .filter(|(_, g)| *g != 0)
                .map(|(n, g)| format!("{n} +{g}%"))
                .collect();
            let _ = writeln!(
                md,
                "- Growth: {}",
                if growth.is_empty() {
                    "none".to_string()
                } else {
                    growth.join(", ")
                }
            );
            let _ = writeln!(
                md,
                "- Base stats: Speed {} / Stamina {} / Power {} / Guts {} / Wit {}",
                i.base[0], i.base[1], i.base[2], i.base[3], i.base[4]
            );
            if let Some(us) = i.unique_skill {
                let summary = kb
                    .skills
                    .get(&us)
                    .map(|s| s.summary.clone())
                    .unwrap_or_default();
                let _ = writeln!(md, "- Unique skill: {} — {summary}", kb.skill_name(us));
            }
            let skills: Vec<String> = i
                .skills
                .iter()
                .map(|s| {
                    let when = if s.potential <= 1 {
                        "innate".to_string()
                    } else {
                        format!("P{}", s.potential)
                    };
                    let locked = if s.potential > u.potential {
                        ", LOCKED"
                    } else {
                        ""
                    };
                    format!("{} ({when}{locked})", kb.skill_name(s.id))
                })
                .collect();
            let _ = writeln!(md, "- Skills: {}", skills.join(", "));
            if !i.event_skills.is_empty() {
                let _ = writeln!(
                    md,
                    "- Event skills: {}",
                    i.event_skills
                        .iter()
                        .map(|s| kb.skill_name(*s))
                        .collect::<Vec<_>>()
                        .join(", ")
                );
            }
            for e in &i.evolved {
                let needs: Vec<String> = e.conditions.iter().map(|c| c.join(" + ")).collect();
                let _ = writeln!(
                    md,
                    "- Evolves: {} → {} (needs {})",
                    kb.skill_name(e.base),
                    kb.skill_name(e.evolved),
                    needs.join(" OR ")
                );
            }
            if !u.notes.is_empty() {
                let _ = writeln!(md, "- Notes: {}", u.notes);
            }
            let _ = writeln!(md);
        }

        let _ = writeln!(md, "## Support cards\n");
        for c in &self.roster.cards {
            let lb = if c.is_mlb() {
                "MLB".to_string()
            } else {
                format!("LB{}", c.lb)
            };
            let _ = writeln!(
                md,
                "### {} [{}] — {} {}, {lb}, Lv {} (id {})",
                c.uma,
                c.title,
                c.rarity.label(),
                c.card_type.label(),
                c.level,
                c.id
            );
            let Some(i) = kb.cards.get(&c.id) else {
                let _ = writeln!(md, "- No knowledge data for this card.\n");
                continue;
            };
            let level = u32::from(c.level);
            let fx: Vec<String> = i
                .effects
                .iter()
                .filter_map(|e| {
                    effect_at(&e.points, level)
                        .filter(|v| *v != 0)
                        .map(|v| format!("{} {v}", e.name))
                })
                .collect();
            let _ = writeln!(md, "- Effects at Lv {}: {}", c.level, fx.join(", "));
            if let Some(ue) = &i.unique {
                let state = if level >= ue.level {
                    "active"
                } else {
                    "NOT active yet"
                };
                let effects: Vec<String> = ue
                    .effects
                    .iter()
                    .map(|e| format!("{} {}", e.name, e.value))
                    .collect();
                let cond = if ue.condition.is_empty() {
                    String::new()
                } else {
                    format!("{}: ", ue.condition)
                };
                let _ = writeln!(
                    md,
                    "- Unique effect (from Lv {}, {state}): {cond}{}",
                    ue.level,
                    effects.join(", ")
                );
            }
            if !i.hints.is_empty() {
                let _ = writeln!(
                    md,
                    "- Skill hints: {}",
                    i.hints
                        .iter()
                        .map(|s| kb.skill_name(*s))
                        .collect::<Vec<_>>()
                        .join(", ")
                );
            }
            if !i.event_skills.is_empty() {
                let _ = writeln!(
                    md,
                    "- Event skills: {}",
                    i.event_skills
                        .iter()
                        .map(|s| kb.skill_name(*s))
                        .collect::<Vec<_>>()
                        .join(", ")
                );
            }
            if !c.notes.is_empty() {
                let _ = writeln!(md, "- Notes: {}", c.notes);
            }
            let _ = writeln!(md);
        }
        md
    }

    /// Rewrite the digest file if its content changed. Returns its path.
    pub(crate) fn write_digest(&self) -> Option<PathBuf> {
        if !self.kb.is_loaded() || self.roster.cards.is_empty() {
            return None;
        }
        let path = self.root.as_ref()?.join(DIGEST_FILE);
        let text = self.roster_digest();
        if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
            std::fs::create_dir_all(path.parent()?).ok()?;
            std::fs::write(&path, text).ok()?;
        }
        Some(path)
    }
}

#[cfg(test)]
mod tests {

    #[test]
    fn digest_resolves_names_and_levels() {
        let a = crate::App::for_tests();
        let d = a.roster_digest();
        assert!(d.contains("### Oguri Cap [Starlight Beat] — 5★, Potential 5"));
        assert!(
            d.contains("| Narita Brian | Maverick | 4 | 5 | A |"),
            "at-a-glance uma row"
        );
        assert!(
            d.contains("| Kitasan Black | Fire at My Heels | SSR | Speed | MLB | 50 | 25 |"),
            "at-a-glance card row"
        );
        assert!(d.contains("Unique skill: Triumphant Pulse"));
        assert!(d.contains("### Kitasan Black [Fire at My Heels] — SSR Speed, MLB, Lv 50"));
        assert!(d.contains("Friendship Bonus 25"));
        assert!(d.contains("LOCKED"), "potential-locked skills are marked");
        assert!(!d.contains("Skill 2"), "every skill id resolves to a name");
    }
}
